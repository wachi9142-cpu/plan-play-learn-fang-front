export const getWorksheet = (id: string) => WORKSHEETS.find((w) => w.id === id);
export const getWorksheetsForPlan = (planId: string) => WORKSHEETS.filter((w) => w.planIds.includes(planId));
export const getWorksheetsByCategory = (c: WorksheetCategory) => WORKSHEETS.filter((w) => w.category === c);

/** แท็กทั้งหมดที่ใช้อยู่ เรียงตามความถี่ */
export function allWorksheetTags() {
  const count = new Map<string, number>();
  for (const w of WORKSHEETS) for (const t of w.tags) count.set(t, (count.get(t) ?? 0) + 1);
  return [...count.entries()].sort((a, b) => b[1] - a[1]).map(([tag, n]) => ({ tag, n }));
}

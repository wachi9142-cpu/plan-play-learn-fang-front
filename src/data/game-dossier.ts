/** แฟ้มข้อมูลของเกมหนึ่งเกม — เติมจาก engine + หมวด แล้วให้ของรายเกมเขียนทับ */
export function getDossier(game: Game): Dossier {
  const own = GAME_DOSSIERS[game.id] ?? {};
  return {
    how: own.how ?? HOW_TO[game.config.engine] ?? HOW_FALLBACK,
    facts: own.facts ?? CATEGORY_FACTS[game.category],
    teacher: own.teacher ?? CATEGORY_TEACHER[game.category],
    origin: own.origin ?? GAME_ORIGINS[game.id] ?? GAME_ORIGINS[game.config.engine],
  };
}

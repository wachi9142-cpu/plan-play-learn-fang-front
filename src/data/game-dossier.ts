/**
 * 📁 แฟ้มข้อมูลเกมเพื่อการเรียนรู้
 *
 * ทุกเกมใช้โครงเดียวกัน แบ่งเป็น 2 ฝั่งชัดเจน
 *  • ฝั่งเด็ก — วิธีเล่น + เกร็ดความรู้ ภาษาง่าย ๆ ประโยคสั้น
 *  • ฝั่งครูและผู้ปกครอง — จุดประสงค์ พัฒนาการ พฤติกรรมที่สังเกตได้ แนวทางต่อยอด และการประเมิน
 *
 * ข้อมูลประกอบมาจาก 3 ชั้น ชั้นล่างสุดเติมให้อัตโนมัติ จึงไม่มีเกมไหนหน้าว่าง
 *  1) ตาม engine  → วิธีเล่น (เกมที่ใช้ engine เดียวกันเล่นเหมือนกัน)
 *  2) ตามหมวดเกม → จุดประสงค์ พัฒนาการ พฤติกรรม ต่อยอด ประเมิน
 *  3) ราย id เกม  → เขียนทับได้ทุกหัวข้อเมื่ออยากละเอียดเป็นพิเศษ
 *
 * ⚠️ ถ้อยคำทุกหัวข้อเขียนแบบ "สิ่งที่ครูสังเกตได้ขณะเล่น" ไม่ใช่คำรับประกันว่า
 *    เล่นเกมแล้วเด็กจะมีทักษะนั้นแน่นอน — ครูเป็นผู้ประเมินเด็กแต่ละคนเอง
 */

export interface HowTo {
  /** ขั้นตอนการเล่น ภาษาเด็ก ประโยคสั้น */
  steps: string[];
  /** เล่นจบเมื่อไร */
  win: string;
}

export interface Fact {
  emoji: string;
  text: string;
}

export interface GrowthArea {
  emoji: string;
  /** ด้านพัฒนาการ */
  area: string;
  text: string;
}

export interface TeacherFile {
  /** จุดประสงค์การเรียนรู้ */
  objective: string[];
  /** พัฒนาการและทักษะที่เกี่ยวข้องกับกิจกรรมนี้ */
  growth: GrowthArea[];
  /** พฤติกรรมที่ครูสังเกตได้ระหว่างเด็กเล่น */
  observe: string[];
  /** คำถามชวนคิดหลังเล่น */
  ask: string[];
  /** กิจกรรมเสริมนอกจอ */
  activity: string[];
  /** แนวทางประเมิน — เป็นข้อสังเกต ไม่ใช่การตัดเกรด */
  assess: string[];
}

export interface Dossier {
  how: HowTo;
  facts: Fact[];
  teacher: TeacherFile;
}

